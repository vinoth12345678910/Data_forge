-- saas-multitenant: tenants, members, teams, projects, usage rollups, billing. Postgres.
-- Money is integer minor units (columns end in _minor); the one currency lives in meta.
--
-- Tenant isolation: every tenant-scoped table has tenant_id and unique (tenant_id, id).
-- Children point at parents with composite FKs (tenant_id, parent_id), so a cross-tenant
-- link is rejected by the database. Global tables (plans, permissions, users) and the
-- plain FK to tenants are the only exceptions.

create table meta (
    id           smallint primary key default 1,
    generated_at timestamptz not null,
    currency     char(3) not null,
    constraint meta_one_row check (id = 1)
);

create table plans (
    id                  bigint generated by default as identity primary key,
    code                text not null unique,
    name                text not null,
    seats               int not null,
    max_projects        int not null,
    monthly_price_minor bigint not null,
    features            text[] not null default '{}',
    constraint plans_limits_positive check (seats > 0 and max_projects > 0),
    constraint plans_price_nonneg check (monthly_price_minor >= 0)
);

create table tenants (
    id           uuid primary key,
    slug         text not null,
    name         text not null,
    plan_id      bigint not null,
    status       text not null,
    timezone     text not null,
    settings     jsonb not null default '{}',
    ip_allowlist cidr[] not null default '{}',
    created_at   timestamptz not null,
    deleted_at   timestamptz,
    constraint tenants_plan_fk foreign key (plan_id) references plans (id),
    constraint tenants_status_valid check (status in ('trialing', 'active', 'suspended', 'closed')),
    constraint tenants_closed_iff_deleted check ((status = 'closed') = (deleted_at is not null))
);
create unique index tenants_active_slug_key on tenants (slug) where deleted_at is null;

create table users (
    id            uuid primary key,
    email         text not null,
    display_name  text not null,
    last_login_ip inet,
    created_at    timestamptz not null,
    deleted_at    timestamptz
);
create unique index users_active_email_key on users (lower(email)) where deleted_at is null;

create table permissions (
    id          bigint generated by default as identity primary key,
    code        text not null unique,
    description text not null
);

create table roles (
    id         bigint generated by default as identity primary key,
    tenant_id  uuid not null,
    name       text not null,
    is_system  boolean not null default false,
    created_at timestamptz not null,
    constraint roles_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint roles_tenant_id_key unique (tenant_id, id),
    constraint roles_tenant_name_key unique (tenant_id, name)
);

-- many-to-many: roles <-> permissions
create table role_permissions (
    tenant_id     uuid not null,
    role_id       bigint not null,
    permission_id bigint not null,
    primary key (role_id, permission_id),
    constraint role_permissions_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint role_permissions_role_fk foreign key (tenant_id, role_id) references roles (tenant_id, id),
    constraint role_permissions_permission_fk foreign key (permission_id) references permissions (id)
);

create table members (
    id         bigint generated by default as identity primary key,
    tenant_id  uuid not null,
    user_id    uuid not null,
    role_id    bigint not null,
    status     text not null,
    invited_at timestamptz not null,
    joined_at  timestamptz,
    deleted_at timestamptz,
    constraint members_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint members_user_fk foreign key (user_id) references users (id),
    constraint members_role_fk foreign key (tenant_id, role_id) references roles (tenant_id, id),
    constraint members_tenant_id_key unique (tenant_id, id),
    constraint members_status_valid check (status in ('invited', 'active', 'suspended', 'removed')),
    constraint members_removed_iff_deleted check ((status = 'removed') = (deleted_at is not null)),
    constraint members_joined_matches_status check (
        (status = 'invited' and joined_at is null)
        or (status in ('active', 'suspended') and joined_at is not null)
        or status = 'removed')
);
create unique index members_active_user_key on members (tenant_id, user_id) where deleted_at is null;

-- self-referencing tree per tenant
create table teams (
    id         bigint generated by default as identity primary key,
    tenant_id  uuid not null,
    parent_id  bigint,
    name       text not null,
    created_at timestamptz not null,
    deleted_at timestamptz,
    constraint teams_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint teams_tenant_id_key unique (tenant_id, id),
    constraint teams_parent_fk foreign key (tenant_id, parent_id) references teams (tenant_id, id),
    constraint teams_not_own_parent check (parent_id <> id)
);
create unique index teams_active_sibling_name_key on teams (tenant_id, coalesce(parent_id, 0), name)
    where deleted_at is null;

-- many-to-many: teams <-> members
create table team_members (
    tenant_id uuid not null,
    team_id   bigint not null,
    member_id bigint not null,
    primary key (team_id, member_id),
    constraint team_members_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint team_members_team_fk foreign key (tenant_id, team_id) references teams (tenant_id, id),
    constraint team_members_member_fk foreign key (tenant_id, member_id) references members (tenant_id, id)
);

create table projects (
    id         bigint generated by default as identity primary key,
    tenant_id  uuid not null,
    team_id    bigint,
    name       text not null,
    slug       text generated always as (lower(regexp_replace(name, '[^a-zA-Z0-9]+', '-', 'g'))) stored,
    settings   jsonb not null default '{}',
    created_by bigint not null,
    created_at timestamptz not null,
    deleted_at timestamptz,
    constraint projects_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint projects_tenant_id_key unique (tenant_id, id),
    constraint projects_team_fk foreign key (tenant_id, team_id) references teams (tenant_id, id),
    constraint projects_creator_fk foreign key (tenant_id, created_by) references members (tenant_id, id)
);
create unique index projects_active_slug_key on projects (tenant_id, slug) where deleted_at is null;

create table api_keys (
    id           uuid primary key,
    tenant_id    uuid not null,
    project_id   bigint not null,
    created_by   bigint not null,
    key_hash     text not null unique,
    scopes       text[] not null,
    created_at   timestamptz not null,
    expires_at   timestamptz,
    revoked_at   timestamptz,
    last_used_ip inet,
    constraint api_keys_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint api_keys_project_fk foreign key (tenant_id, project_id) references projects (tenant_id, id),
    constraint api_keys_creator_fk foreign key (tenant_id, created_by) references members (tenant_id, id),
    constraint api_keys_expiry_after_creation check (expires_at is null or expires_at > created_at),
    constraint api_keys_scopes_nonempty check (cardinality(scopes) > 0)
);

-- raw usage; usage_daily rolls it up per local day in the tenant's time zone
create table usage_events (
    id          bigint generated by default as identity primary key,
    tenant_id   uuid not null,
    project_id  bigint not null,
    kind        text not null,
    quantity    int not null,
    occurred_at timestamptz not null,
    source_ip   inet,
    attrs       jsonb not null default '{}',
    constraint usage_events_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint usage_events_project_fk foreign key (tenant_id, project_id) references projects (tenant_id, id),
    constraint usage_events_kind_valid check (kind in ('api_call', 'storage_mb', 'build_minute')),
    constraint usage_events_quantity_positive check (quantity > 0),
    constraint usage_events_attrs_object check (jsonb_typeof(attrs) = 'object')
);

create table usage_daily (
    tenant_id      uuid not null,
    project_id     bigint not null,
    day            date not null,
    kind           text not null,
    event_count    int not null,
    quantity_total bigint not null,
    primary key (tenant_id, project_id, day, kind),
    constraint usage_daily_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint usage_daily_project_fk foreign key (tenant_id, project_id) references projects (tenant_id, id),
    constraint usage_daily_kind_valid check (kind in ('api_call', 'storage_mb', 'build_minute')),
    constraint usage_daily_counts_positive check (event_count > 0 and quantity_total > 0)
);

create table subscriptions (
    id            bigint generated by default as identity primary key,
    tenant_id     uuid not null,
    plan_id       bigint not null,
    status        text not null,
    period_start  timestamptz not null,
    period_end    timestamptz not null,
    trial_ends_at timestamptz,
    cancelled_at  timestamptz,
    constraint subscriptions_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint subscriptions_plan_fk foreign key (plan_id) references plans (id),
    constraint subscriptions_tenant_id_key unique (tenant_id, id),
    constraint subscriptions_status_valid check (status in ('trialing', 'active', 'past_due', 'cancelled')),
    constraint subscriptions_period_ordered check (period_start < period_end)
);
-- live = trialing, active or past_due: one per tenant
create unique index subscriptions_one_live_key on subscriptions (tenant_id)
    where status in ('trialing', 'active', 'past_due');

create table invoices (
    id              uuid primary key,
    tenant_id       uuid not null,
    subscription_id bigint not null,
    number          text not null,
    status          text not null,
    period_start    timestamptz not null,
    period_end      timestamptz not null,
    issued_at       timestamptz,
    due_at          timestamptz,
    paid_at         timestamptz,
    subtotal_minor  bigint not null,
    tax_minor       bigint not null,
    total_minor     bigint not null,
    constraint invoices_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint invoices_subscription_fk foreign key (tenant_id, subscription_id)
        references subscriptions (tenant_id, id),
    constraint invoices_tenant_id_key unique (tenant_id, id),
    constraint invoices_tenant_number_key unique (tenant_id, number),
    constraint invoices_status_valid check (status in ('draft', 'open', 'paid', 'void', 'uncollectible')),
    constraint invoices_period_ordered check (period_start < period_end),
    constraint invoices_total_formula check (total_minor = subtotal_minor + tax_minor),
    constraint invoices_status_times_valid check (
        (status = 'draft' and issued_at is null and paid_at is null)
        or (status in ('open', 'uncollectible') and issued_at is not null and due_at is not null and paid_at is null)
        or (status = 'paid' and issued_at is not null and paid_at is not null and paid_at >= issued_at)
        or (status = 'void' and paid_at is null))
);

create table invoice_lines (
    id                bigint generated by default as identity primary key,
    tenant_id         uuid not null,
    invoice_id        uuid not null,
    kind              text not null,
    plan_id           bigint,
    description       text not null,
    quantity          int not null,
    unit_amount_minor bigint not null,
    amount_minor      bigint not null,
    period_start      timestamptz not null,
    period_end        timestamptz not null,
    constraint invoice_lines_tenant_fk foreign key (tenant_id) references tenants (id),
    constraint invoice_lines_invoice_fk foreign key (tenant_id, invoice_id) references invoices (tenant_id, id),
    constraint invoice_lines_plan_fk foreign key (plan_id) references plans (id),
    constraint invoice_lines_kind_valid check (kind in ('plan', 'proration_charge', 'proration_credit', 'usage')),
    constraint invoice_lines_quantity_positive check (quantity > 0),
    constraint invoice_lines_period_ordered check (period_start < period_end),
    constraint invoice_lines_amount_formula check (amount_minor = quantity::bigint * unit_amount_minor)
);
