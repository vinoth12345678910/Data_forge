/**
 * P2.3 gate: the manifest matches the rows loaded exactly (counts and keys per table), the database copy
 * equals the local copy, a crash between commit and rename is repaired from the database, and a failed
 * load leaves no manifest, no files and no rows. The load itself is the test-only helper (P2.4 repeats this
 * with the product loader).
 */
@Tag("containers")
@Testcontainers(disabledWithoutDocker = false)
class ManifestContainerTest {

    @Container
    static final PostgreSQLContainer PG = new PostgreSQLContainer("postgres:16-alpine");

    static final String CLOCK = "2025-01-01T00:00:00Z";
    static final String CONFIG = "version: 1\nseed: 42\n";

    static final String DDL = """
        create table users (id bigint generated by default as identity primary key, email text not null unique);
        create table teams (id bigint primary key, name text not null);
        create table tokens (id uuid primary key, user_id bigint not null references users (id), label text not null);
        create table memberships (
            user_id bigint not null references users (id),
            team_id bigint not null references teams (id),
            primary key (user_id, team_id));
        create table aliases (code text not null unique, note text);
        """;

    static int dbs;

    static String jdbc(String db) {
        return PG.getJdbcUrl().replaceFirst("/[^/?]+(\\?|$)", "/" + db + "$1");
    }

    static Connection open(String db) throws SQLException {
        return DriverManager.getConnection(jdbc(db) + (jdbc(db).contains("?") ? "&" : "?") + "stringtype=unspecified",
            PG.getUsername(), PG.getPassword());
    }

    static String fresh(String ddl) throws Exception {
        String db = "mf_" + (dbs++);
        try (Connection c = open("test"); Statement s = c.createStatement()) {
            s.execute("create database " + db);
        }
        try (Connection c = open(db); Statement s = c.createStatement()) {
            s.execute(ddl);
        }
        return db;
    }

    static Config conf(Map<String, Integer> rows, String... keep) {
        Map<String, Config.TableConf> t = new TreeMap<>();
        rows.forEach((k, v) -> t.put(k, new Config.TableConf(v, false, new TreeMap<>())));
        for (String k : keep) {
            t.put(k, new Config.TableConf(null, true, new TreeMap<>()));
        }
        return new Config(1, 42, CLOCK, "en_IN", null, "x.sql", t);
    }

    static final Map<String, Integer> ROWS = Map.of("users", 40, "teams", 5, "tokens", 30, "memberships", 20, "aliases", 12);

    static long count(Connection c, String table) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet r = s.executeQuery("select count(*) from \"" + table + "\"")) {
            r.next();
            return r.getLong(1);
        }
    }

    static String sha(Path dir, String run, boolean keys) throws Exception {
        MessageDigest d = MessageDigest.getInstance("SHA-256");
        d.update(Files.readAllBytes(dir.resolve(run + ".json")));
        if (keys) {
            d.update(Files.readAllBytes(dir.resolve(run + ".keys")));
        }
        return HexFormat.of().formatHex(d.digest());
    }

    static Set<String> manifestKeys(Manifest.Tbl t) {
        Set<String> out = new TreeSet<>();
        if (t.form().equals("ranges")) {
            for (long[] r : t.ranges()) {
                for (long v = r[0]; v <= r[1]; v++) {
                    out.add("[" + v + "]");
                }
            }
        } else {
            t.keys().each(out::add);
        }
        return out;
    }

    /** The keys of a table as the manifest writes them (JSON array text), read from the database. */
    static Set<String> dbKeys(Connection c, Manifest.Tbl t) throws SQLException {
        Set<String> out = new TreeSet<>();
        String cols = String.join(", ", t.key().stream().map(k -> "\"" + k + "\"").toList());
        try (Statement s = c.createStatement(); ResultSet r = s.executeQuery("select " + cols + " from \"" + t.name() + "\"")) {
            while (r.next()) {
                List<String> parts = new ArrayList<>();
                for (int i = 1; i <= t.key().size(); i++) {
                    String v = r.getString(i);
                    boolean num = r.getMetaData().getColumnTypeName(i).matches("int[248]|serial|bigserial");
                    parts.add(num ? v : "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"") + "\"");
                }
                out.add("[" + String.join(",", parts) + "]");
            }
        }
        return out;
    }

    /** Stages the files, loads and writes the manifest in one transaction, commits and publishes. */
    static Manifest runOnce(Connection c, SchemaGraph g, Config conf, Path dir, boolean publish) throws Exception {
        RowGen gen = RowGen.of(g, conf);
        Manifest m = ManifestBuilder.build(g, conf, gen, CONFIG, "2026-11-11T10:00:00Z", "test", Sequences.before(c, g));
        ManifestFile.Staged st = ManifestFile.stage(dir, m);
        c.setAutoCommit(false);
        try {
            TestInsert.loadInto(c, g, gen);
            ManifestDb.write(c, m, st.sha256());
            Sequences.apply(c, m.sequences());
            c.commit();
        } catch (Exception e) {
            c.rollback();
            st.discard();
            throw e;
        }
        if (publish) {
            st.publish();
        }
        return m;
    }

    @Test
    void manifestMatchesTheLoadedRowsAndBothCopiesAgree(@TempDir Path dir) throws Exception {
        String db = fresh(DDL);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        try (Connection c = open(db)) {
            Manifest m = runOnce(c, g, conf(ROWS), dir, true);
            assertEquals(5, m.tables().size());
            for (Manifest.Tbl t : m.tables()) {
                assertEquals((long) ROWS.get(t.name()), t.rows(), t.name());
                assertEquals(count(c, t.name()), t.rows(), "row count in the database: " + t.name());
                assertEquals(0, t.rowsBefore());
                assertEquals(dbKeys(c, t), manifestKeys(t), "keys of " + t.name());
            }
            Map<String, String> form = new TreeMap<>();
            m.tables().forEach(t -> form.put(t.name(), t.form() + t.key()));
            assertEquals("ranges[id]", form.get("users"));
            assertEquals("ranges[id]", form.get("teams"));
            assertEquals("list[id]", form.get("tokens"));
            assertEquals("list[user_id, team_id]", form.get("memberships"));
            assertEquals("list[code]", form.get("aliases"));

            // the database copy
            Manifest db2 = ManifestDb.read(c, m.runId());
            assertEquals(m.seed(), db2.seed());
            assertEquals(m.configSha(), db2.configSha());
            assertEquals(m.schemaSha(), db2.schemaSha());
            assertEquals(m.tables().size(), db2.tables().size());
            for (int i = 0; i < m.tables().size(); i++) {
                assertEquals(m.tables().get(i).rows(), db2.tables().get(i).rows());
                assertEquals(manifestKeys(m.tables().get(i)), manifestKeys(db2.tables().get(i)));
            }
            // the local copy: same hash as recorded in the database
            assertEquals(ManifestDb.fileSha(c, m.runId()), sha(dir, m.runId(), true));
            assertTrue(Files.exists(dir.resolve(m.runId() + ".json")));
            assertFalse(Files.exists(dir.resolve(m.runId() + ".json.part")));
            // sequences left at the last generated id
            try (Statement s = c.createStatement(); ResultSet r = s.executeQuery("select last_value, is_called from users_id_seq")) {
                r.next();
                assertEquals(40, r.getLong(1));
                assertTrue(r.getBoolean(2));
            }
            assertEquals("users_id_seq", m.sequences().get(0).name().replaceFirst(".*\\.", ""));
            assertEquals(1L, m.sequences().get(0).beforeLast());
            assertFalse(m.sequences().get(0).beforeCalled());
        }
    }

    @Test
    void aCrashBetweenCommitAndRenameIsRepairedFromTheDatabase(@TempDir Path dir) throws Exception {
        String db = fresh(DDL);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        try (Connection c = open(db)) {
            Manifest m = runOnce(c, g, conf(ROWS), dir, false);   // committed, never renamed
            assertFalse(Files.exists(dir.resolve(m.runId() + ".json")), "no final file after the simulated crash");
            assertTrue(Files.exists(dir.resolve(m.runId() + ".json.part")));
            String sha = ManifestFile.rebuild(c, dir, m.runId());
            assertEquals(ManifestDb.fileSha(c, m.runId()), sha);
            assertEquals(sha, sha(dir, m.runId(), true));
            assertFalse(Files.exists(dir.resolve(m.runId() + ".json.part")), "stale part files are removed");
            // and a lost file can always be rebuilt again, byte for byte
            byte[] before = Files.readAllBytes(dir.resolve(m.runId() + ".json"));
            Files.delete(dir.resolve(m.runId() + ".json"));
            Files.delete(dir.resolve(m.runId() + ".keys"));
            ManifestFile.rebuild(c, dir, m.runId());
            assertTrue(java.util.Arrays.equals(before, Files.readAllBytes(dir.resolve(m.runId() + ".json"))));
        }
    }

    @Test
    void aFailedLoadLeavesNoRowsNoManifestAndNoFiles(@TempDir Path dir) throws Exception {
        String db = fresh(DDL);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        Config conf = conf(ROWS);
        try (Connection c = open(db)) {
            RowGen gen = RowGen.of(g, conf);
            Manifest m = ManifestBuilder.build(g, conf, gen, CONFIG, "2026-11-11T10:00:00Z", "test", Sequences.before(c, g));
            ManifestFile.Staged st = ManifestFile.stage(dir, m);
            c.setAutoCommit(false);
            assertThrows(IllegalStateException.class, () -> {
                try {
                    TestInsert.loadInto(c, g, gen);
                    ManifestDb.write(c, m, st.sha256());
                    throw new IllegalStateException("the load failed after the manifest was written");
                } catch (SQLException e) {
                    throw new IllegalStateException(e);
                }
            });
            c.rollback();
            st.discard();
            c.setAutoCommit(true);
            for (String t : ROWS.keySet()) {
                assertEquals(0, count(c, t), t);
            }
            try (Statement s = c.createStatement();
                 ResultSet r = s.executeQuery("select count(*) from information_schema.schemata where schema_name = '_dataforge'")) {
                r.next();
                assertEquals(0, r.getLong(1), "_dataforge must not survive a failed first load");
            }
            try (var files = Files.list(dir)) {
                assertEquals(0, files.count(), "no manifest files left behind");
            }
        }
    }

    @Test
    void aSecondManifestWithTheSameRunIdFailsAndLeavesTheFirstIntact(@TempDir Path dir) throws Exception {
        String db = fresh(DDL);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        try (Connection c = open(db)) {
            Manifest m = runOnce(c, g, conf(ROWS), dir, true);
            c.setAutoCommit(false);
            assertThrows(SQLException.class, () -> ManifestDb.write(c, m, "x"));
            c.rollback();
            c.setAutoCommit(true);
            assertEquals(ManifestDb.fileSha(c, m.runId()), sha(dir, m.runId(), true));
            assertEquals(5, ManifestDb.read(c, m.runId()).tables().size());
        }
    }

    @Test
    void aTableWithNoUsableKeyIsRefusedWithAnInstruction(@TempDir Path dir) throws Exception {
        String db = fresh(DDL + "create table audit (note text, at timestamptz);");
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        Map<String, Integer> rows = new TreeMap<>(ROWS);
        rows.put("audit", 10);
        {
            ManifestError e = assertThrows(ManifestError.class,
                () -> ManifestBuilder.build(g, conf(rows), RowGen.of(g, conf(rows)), CONFIG, "2026-11-11T10:00:00Z", "test", List.of()));
            assertEquals("table audit has no primary key or unique not-null key; cleanup could not tell its rows apart. "
                + "Add a key or mark the table keep in forge.yml.", e.getMessage());
            // keep tables cannot be tested here: RowGen does not generate kept tables yet (Phase 1 limit).
        }
    }
}
