import org.testcontainers.postgresql.PostgreSQLContainer;

/** P2.4 gate: specific shapes (GENERATED ALWAYS ids, null-then-update cycle, self-reference) and atomicity. */
@Tag("containers")
@Testcontainers(disabledWithoutDocker = false)
class LoaderShapesContainerTest {

    @Container
    static final PostgreSQLContainer PG = new PostgreSQLContainer("postgres:16-alpine");

    static int dbs;

    static String jdbc(String db) {
        return PG.getJdbcUrl().replaceFirst("/[^/?]+(\\?|$)", "/" + db + "$1");
    }

    static String fresh(String ddl) throws Exception {
        String db = "sh_" + (dbs++);
        try (Connection c = DriverManager.getConnection(jdbc("test"), PG.getUsername(), PG.getPassword()); Statement s = c.createStatement()) {
            s.execute("create database " + db);
        }
        try (Connection c = DriverManager.getConnection(jdbc(db), PG.getUsername(), PG.getPassword()); Statement s = c.createStatement()) {
            s.execute(ddl);
        }
        return db;
    }

    static Config conf(Map<String, Integer> rows) {
        Map<String, Config.TableConf> t = new TreeMap<>();
        rows.forEach((k, v) -> t.put(k, new Config.TableConf(v, false, new TreeMap<>())));
        return new Config(1, 7, "2025-01-01T00:00:00Z", "en_IN", null, "x.sql", t);
    }

    static long one(Connection c, String sql) throws Exception {
        try (Statement s = c.createStatement(); ResultSet r = s.executeQuery(sql)) {
            r.next();
            return r.getLong(1);
        }
    }

    static final String SHAPES = """
        create table a (id bigint generated always as identity primary key, boss_id bigint references a (id),
                        next_b bigint, name text not null);
        create table b (id bigint generated by default as identity primary key, a_id bigint not null references a (id),
                        note text not null);
        alter table a add constraint a_next_b_fk foreign key (next_b) references b (id);
        """;

    @Test
    void generatedAlwaysIdsSelfReferenceAndANullThenUpdateCycle(@TempDir Path dir) throws Exception {
        String db = fresh(SHAPES);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        Config conf = conf(Map.of("a", 30, "b", 40));
        RowGen gen = RowGen.of(g, conf);
        assertTrue(gen.plan().breaks().stream().anyMatch(b -> b.how().equals("null-then-update")),
            "the cycle must be broken by null-then-update: " + gen.plan().breaks());
        try (Connection c = DriverManager.getConnection(jdbc(db), PG.getUsername(), PG.getPassword())) {
            PgLoader.load(c, g, conf, gen, "x", "test", dir);
            assertEquals(30, one(c, "select count(*) from a"));
            assertEquals(40, one(c, "select count(*) from b"));
            assertTrue(one(c, "select count(*) from a where next_b is not null") > 0, "the update must have filled next_b");
            assertEquals(0, one(c, "select count(*) from a x where x.boss_id is not null and not exists (select 1 from a y where y.id = x.boss_id)"));
            assertEquals(0, one(c, "select count(*) from a x where x.next_b is not null and not exists (select 1 from b y where y.id = x.next_b)"));
            assertEquals(30, one(c, "select last_value from a_id_seq"), "sequence left at the last id");
            assertTrue(StructureCheck.violations(c, g).isEmpty());
        }
    }

    @Test
    void aFailureInTheMiddleLeavesNothingBehind(@TempDir Path dir) throws Exception {
        String db = fresh("""
            create table p (id bigint primary key, name text not null);
            create table q (id bigint primary key, p_id bigint not null references p (id), note text not null);
            create function stop() returns trigger language plpgsql as $$
              begin if new.id = 17 then raise exception 'boom at 17'; end if; return new; end $$;
            create trigger q_stop before insert on q for each row execute function stop();
            """);
        SchemaGraph g = PgReader.read(new Db(jdbc(db), PG.getUsername(), PG.getPassword()), "public");
        Config conf = conf(Map.of("p", 20, "q", 30));
        try (Connection c = DriverManager.getConnection(jdbc(db), PG.getUsername(), PG.getPassword())) {
            LoadError e = assertThrows(LoadError.class, () -> PgLoader.load(c, g, conf, RowGen.of(g, conf), "x", "test", dir.resolve("m")));
            assertTrue(e.getMessage().contains("q") && e.getMessage().contains("boom"), e.getMessage());
            assertEquals(0, one(c, "select count(*) from p"));
            assertEquals(0, one(c, "select count(*) from q"));
            assertEquals(0, one(c, "select count(*) from information_schema.schemata where schema_name = '_dataforge'"));
            try (var files = Files.list(dir.resolve("m"))) {
                assertEquals(0, files.count(), "no manifest files left behind");
            }
            assertTrue(c.getAutoCommit(), "the connection is left as found");
        }
    }
}
