/**
 * P2.5 gate: on data GENERATED by Data Forge (not hand-written) for events-merch and ecommerce, every in-scope
 * rule PASSES under both oracles (our verify pass and the golden hand-written violations_sql), the structure holds,
 * and the output is deterministic with rules on. saas-multitenant is generated, loaded and REPORTED, not a gate.
 */
@Tag("containers")
@Testcontainers(disabledWithoutDocker = false)
class RuleGenContainerTest {

    @Container
    static final PostgreSQLContainer PG =
        new PostgreSQLContainer("postgres:16-alpine").withUsername("postgres").withPassword("pw");

    static int counter;

    @BeforeAll
    static void password() {
        Forge.env = name -> name.equals("TEST_PG_PASSWORD") ? "pw" : null;
    }

    @AfterAll
    static void restore() {
        Forge.env = System::getenv;
    }

    static Path golden(String rel) {
        return Path.of(System.getProperty("golden.dir"), rel);
    }

    static String base() {
        return "jdbc:postgresql://" + PG.getHost() + ":" + PG.getMappedPort(5432) + "/";
    }

    /** forge init's zero-config file (row counts) with the golden's Phase 2 rules put on top. */
    /**
     * A5: the two ecommerce inventory rules are checked by verify (both oracles, seed and broken fixtures: RuleGoldenContainerTest,
     * VerifyOracleContainerTest) but not generated. inventory has check (reserved <= on_hand) and both columns are derived, so the
     * generator refuses them (a floor on opening_qty would be needed; decided verify-only for now, see docs/LIMITS_REGISTER.md A5).
     */
    static final Set<String> VERIFY_ONLY = Set.of("inventory_reserved_matches_active", "stock_on_hand_matches_movements");

    static Config configWithRules(String name, Path dir, List<Config.RuleConf> rules) throws Exception {
        Path ddl = golden(name + "/schema.sql");
        Path yml = dir.resolve("forge.yml");
        StringWriter err = new StringWriter();
        int code = Forge.run(new PrintWriter(new StringWriter(), true), new PrintWriter(err, true), "init", "--ddl", ddl.toString(),
            "--scratch-url", "postgres://" + PG.getHost() + ":" + PG.getMappedPort(5432) + "/postgres", "--env", "test",
            "--user", "postgres", "--password-env", "TEST_PG_PASSWORD", "--out", yml.toString());
        assertEquals(0, code, err.toString());
        Config c = ConfigReader.read(Files.readString(yml));
        return new Config(c.version(), c.seed(), "2026-06-01T00:00:00Z", c.locale(), c.connection(), c.ddl(), c.tables(), rules);
    }

    static Map<String, String> goldenSql(String name) throws Exception {
        JsonNode root = new ObjectMapper(new YAMLFactory()).readTree(golden(name + "/expected.yml").toFile());
        Map<String, String> out = new TreeMap<>();
        for (JsonNode r : root.get("rules")) {
            if (r.has("violations_sql")) {
                out.put(r.get("name").asText(), r.get("violations_sql").asText());
            }
        }
        return out;
    }

    static Set<String> keys(Connection c, String sql) throws Exception {
        Set<String> out = new TreeSet<>();
        try (Statement s = c.createStatement(); ResultSet r = s.executeQuery(sql)) {
            while (r.next()) {
                out.add(r.getString(1));
            }
        }
        return out;
    }

    static Connection fresh(Path ddl) throws Exception {
        String db = "rg_" + (counter++);
        try (Connection c = DriverManager.getConnection(base() + "postgres", "postgres", "pw"); Statement s = c.createStatement()) {
            s.execute("create database " + db);
        }
        Connection c = DriverManager.getConnection(base() + db, "postgres", "pw");
        try (Statement s = c.createStatement()) {
            s.setEscapeProcessing(false);
            s.execute(Files.readString(ddl));
        }
        return c;
    }

    @ParameterizedTest
    @ValueSource(strings = {"events-merch", "ecommerce"})
    void generatedDataPassesEveryInScopeRuleUnderBothOracles(String name, @TempDir Path dir) throws Exception {
        Path ddl = golden(name + "/schema.sql");
        Config p2 = ConfigReader.read(Files.readString(golden(name + "/phase2.forge.yml")));
        SchemaGraph g = DdlReader.read(ddl, new Db(base() + "postgres", "postgres", "pw"));
        Config conf = configWithRules(name, dir, p2.rules().stream().filter(r -> !VERIFY_ONLY.contains(r.name())).toList());
        List<Rule> rules = RuleSet.check(conf.rules(), g);
        assertEquals(name.equals("events-merch") ? 6 : 9, rules.size());

        RowGen gen = RowGen.of(g, conf, rules);
        byte[] first = Out.bytes(gen);
        assertArrayEquals(first, Out.bytes(RowGen.of(g, conf, rules)), "same seed and spec, rules on: byte-identical");

        try (Connection c = fresh(ddl)) {
            PgLoader.load(c, g, conf, gen, "x", "test", dir.resolve("m"));
            List<String> bad = StructureCheck.violations(c, g);
            assertTrue(bad.isEmpty(), "structure: " + bad);
            Report rep = Verifier.run(c, g, rules, 5, 120);
            Map<String, String> gold = goldenSql(name);
            List<String> problems = new ArrayList<>();
            for (RuleResult r : rep.results()) {
                if (!r.status().equals("PASS")) {
                    problems.add("our verify: " + r.name() + " " + r.status() + " " + r.violations() + " " + r.sample() + " " + r.error());
                }
                if (r.checked() == 0) {
                    problems.add("our verify: " + r.name() + " checked no rows");
                }
            }
            for (Rule r : rules) {
                Set<String> theirs = keys(c, gold.get(r.name()));
                if (!theirs.isEmpty()) {
                    problems.add("golden SQL: " + r.name() + " flags " + theirs.size() + " rows, e.g. "
                        + theirs.stream().limit(5).toList());
                }
                Set<String> ours = keys(c, RuleSql.compile(r, g).violations());
                if (!ours.equals(theirs)) {
                    problems.add("oracles disagree on " + r.name());
                }
            }
            assertEquals(List.of(), problems);
        }
    }

    /** Not a gate: generate and load saas-multitenant with no rules, then run every golden query and print the result. */
    @Test
    void saasMultitenantIsRunAndReported(@TempDir Path dir) throws Exception {
        Path ddl = golden("saas-multitenant/schema.sql");
        SchemaGraph g = DdlReader.read(ddl, new Db(base() + "postgres", "postgres", "pw"));
        Config conf = configWithRules("saas-multitenant", dir, List.of());
        try (Connection c = fresh(ddl)) {
            PgLoader.load(c, g, conf, RowGen.of(g, conf), "x", "test", dir.resolve("m"));
            assertTrue(StructureCheck.violations(c, g).isEmpty());
            int pass = 0;
            int fail = 0;
            StringBuilder sb = new StringBuilder();
            for (Map.Entry<String, String> e : goldenSql("saas-multitenant").entrySet()) {
                try {
                    int n = keys(c, e.getValue()).size();
                    if (n == 0) {
                        pass++;
                    } else {
                        fail++;
                        sb.append("  ").append(e.getKey()).append(" flags ").append(n).append(" rows\n");
                    }
                } catch (java.sql.SQLException ex) {
                    fail++;
                    sb.append("  ").append(e.getKey()).append(" ERROR ").append(ex.getMessage().replace('\n', ' ')).append('\n');
                }
            }
            System.out.println("SAAS REPORT (not a gate): " + pass + " golden query rules clean, " + fail + " flag rows or error\n" + sb);
        }
    }
}
