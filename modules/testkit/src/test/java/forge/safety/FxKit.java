/**
 * Purpose-built fixtures and small helpers for the safety tests of groups H to L (own DDL per dialect, because the golden
 * events-merch of MySQL and SQLite has no auto-increment ids, no soft-delete column, no view and no trigger). Plain SQL and
 * files only; no product class.
 */
final class FxKit {

    private FxKit() {}

    static final String HEAD = "version: 1\nseed: 42\nclock: \"2026-06-01T00:00:00Z\"\ntables:\n";

    /** A config body: table -> rows. */
    static String config(Object... tableRows) {
        StringBuilder b = new StringBuilder(HEAD);
        for (int i = 0; i < tableRows.length; i += 2) {
            b.append("  ").append(tableRows[i]).append(":\n    rows: ").append(tableRows[i + 1]).append('\n');
        }
        return b.toString();
    }

    private static String idCol(Dialect d) {
        return switch (d) {
            case PG -> "id bigint generated by default as identity primary key";
            case MY -> "id bigint auto_increment primary key";
            case SQ -> "id integer primary key autoincrement";
        };
    }

    private static String ts(Dialect d) {
        return d == Dialect.MY ? "datetime" : d == Dialect.PG ? "timestamptz" : "timestamp";
    }

    // ---------------------------------------------------------------- rd: users with an identity id, notes, a real table

    /** rd_user (identity id), rd_note (child of rd_user), rd_real (a table the load does not fill and real rows live in). */
    static void rd(Fx fx, long users, long notes) {
        Dialect d = fx.d;
        fx.ddl("create table rd_user (" + idCol(d) + ", email varchar(100) not null unique, full_name varchar(100) not null)",
            "create table rd_note (id bigint primary key, user_id bigint not null, body varchar(200) not null,"
                + " constraint rd_note_user_fk foreign key (user_id) references rd_user (id))",
            "create table rd_real (id bigint primary key, email varchar(100) not null, label varchar(100) not null)");
        fx.custom = config("rd_user", users, "rd_note", notes, "rd_real", 0);
    }

    /** Two real rows in rd_real (the "pre-run state" is not all zeros). */
    static void rdRealRows(Fx fx) {
        fx.insert("rd_real", "id", 1, "email", "keep1@company.test", "label", "pre-existing real row one");
        fx.insert("rd_real", "id", 2, "email", "keep2@company.test", "label", "pre-existing real row two");
    }

    /** A real rd_user with an explicit id. MySQL turns an explicit 0 into a generated id unless NO_AUTO_VALUE_ON_ZERO is set for the session. */
    static void rdUser(Fx fx, long id) {
        String insert = "insert into rd_user (id, email, full_name) values (" + id + ", 'real" + id + "@company.test', 'Real Person " + id + "')";
        if (fx.d == Dialect.MY) {
            fx.sql("set sql_mode = concat(@@sql_mode, ',NO_AUTO_VALUE_ON_ZERO')", insert);
        } else {
            fx.sql(insert);
        }
    }

    // ---------------------------------------------------------------- fi: a failure that can be switched on and off

    static final long FI_PARENTS = 30;
    static final long FI_CHILDREN = 60;
    /** The parent id whose delete makes the trigger delete a real bystander row. */
    static final long FI_BOOM = 25;

    /** fi_parent (identity), fi_child (child), bystander and unrelated (tables only real rows live in). */
    static void fi(Fx fx) {
        Dialect d = fx.d;
        fx.ddl("create table fi_parent (" + idCol(d) + ", label varchar(100) not null)",
            "create table fi_child (id bigint primary key, parent_id bigint not null, note varchar(100) not null,"
                + " constraint fi_child_parent_fk foreign key (parent_id) references fi_parent (id))",
            "create table bystander (id bigint primary key, note varchar(100) not null)",
            "create table unrelated (id bigint primary key, note varchar(100) not null)");
        fx.custom = config("fi_parent", FI_PARENTS, "fi_child", FI_CHILDREN, "bystander", 0, "unrelated", 0);
        fx.backupCmd = "true";
        fx.cleanup.put("batch_rows", "10");
        fx.cleanup.put("allow_triggers", "[fi_parent]");
    }

    /** A real row of bystander the trigger will delete when fi_parent FI_BOOM is deleted. */
    static void fiBystander(Fx fx) {
        fx.insert("bystander", "id", 1, "note", "real bystander row");
    }

    /** The failure: deleting fi_parent FI_BOOM also deletes the real bystander row 1 (an allowed trigger that overreaches). */
    static void fiBoomOn(Fx fx) {
        switch (fx.d) {
            case PG -> fx.ddl("create function fi_boom() returns trigger language plpgsql as $$ begin if old.id = " + FI_BOOM
                + " then delete from bystander where id = 1; end if; return old; end $$",
                "create trigger fi_parent_del after delete on fi_parent for each row execute function fi_boom()");
            case MY -> fx.ddl("create trigger fi_parent_del AFTER DELETE ON fi_parent for each row begin if old.id = " + FI_BOOM
                + " then delete from bystander where id = 1; end if; end");
            case SQ -> fx.ddl("create trigger fi_parent_del AFTER DELETE ON fi_parent for each row when old.id = " + FI_BOOM
                + " begin delete from bystander where id = 1; end");
        }
    }

    static void fiBoomOff(Fx fx) {
        switch (fx.d) {
            case PG -> fx.ddl("drop trigger fi_parent_del on fi_parent", "drop function fi_boom()");
            default -> fx.ddl("drop trigger fi_parent_del");
        }
    }

    // ---------------------------------------------------------------- kx: soft delete column, view, trigger, child

    static void kx(Fx fx, long users, long orders) {
        Dialect d = fx.d;
        fx.ddl("create table kx_user (id bigint primary key, email varchar(100) not null unique, full_name varchar(100) not null,"
                + " created_at " + ts(d) + " not null, deleted_at " + ts(d) + ")",
            "create table kx_order (id bigint primary key, user_id bigint not null, note varchar(100) not null,"
                + " constraint kx_order_user_fk foreign key (user_id) references kx_user (id))",
            "create table kx_log (id bigint primary key, msg varchar(50) not null)",
            "create view kx_user_v as select id, email from kx_user");
        switch (d) {
            case PG -> fx.ddl("create function kx_audit() returns trigger language plpgsql as $$ begin insert into kx_log (id, msg)"
                + " values (old.id, 'gone'); return old; end $$",
                "create trigger kx_order_del after delete on kx_order for each row execute function kx_audit()");
            case MY -> fx.ddl("create trigger kx_order_del AFTER DELETE ON kx_order for each row insert into kx_log (id, msg) values (old.id, 'gone')");
            case SQ -> fx.ddl("create trigger kx_order_del AFTER DELETE ON kx_order for each row begin insert into kx_log (id, msg)"
                + " values (old.id, 'gone'); end");
        }
        fx.custom = config("kx_user", users, "kx_order", orders, "kx_log", 0);
        fx.backupCmd = "true";
    }

    // ---------------------------------------------------------------- pu: purge fixtures

    /** pu_user (40 manifest users after the load) and pu_note (a child table with no generated rows). */
    static void pu(Fx fx, long users) {
        fx.ddl("create table pu_user (id bigint primary key, email varchar(100) not null unique, full_name varchar(100) not null)",
            "create table pu_note (id bigint primary key, user_id bigint not null, body varchar(100) not null,"
                + " constraint pu_note_user_fk foreign key (user_id) references pu_user (id))");
        fx.custom = config("pu_user", users, "pu_note", 0);
        fx.backupCmd = "true";
        fx.cleanup.put("purge", "\n    - { name: smoke_users, table: pu_user, where: \"pu_user.id <= 10\" }");
    }


    // ---------------------------------------------------------------- partial run (the fi fixture)

    /**
     * Brings an fi fixture (after generate) into the partial state: a real bystander row, the failing trigger, a clean dry run and a
     * run that must stop as partial (exit 3, cascade_overreach, state partial in the database). Returns the rows left to delete
     * (counted by SQL).
     */
    static long partialRun(Fx fx, String step) {
        fiBystander(fx);
        fiBoomOn(fx);
        Result dry = fx.dry().expect(step + " dry run (the trigger is allowed)", 0);
        assertEquals(false, dry.field(step + " dry run", "blocked").asBoolean(), step + " dry run: blocked");
        Result r = fx.runOk().expect(step + " run with the failing trigger", 3, "cascade_overreach");
        assertEquals("partial", r.field(step + " run", "state").asText(), step + " run: data.state");
        assertEquals("partial", fx.scalar("select state from " + fx.d.meta("runs")), step + ": _dataforge runs.state");
        long left = fx.count("fi_parent") + fx.count("fi_child");
        assertTrue(left > 0 && left < fx.total(), step + ": rows left " + left + " of " + fx.total() + " (some batches committed, some not)");
        assertEquals(0, fx.count("fi_child"), step + ": the child table was deleted first and its batches committed");
        assertEquals(1, fx.count("fi_parent where id = " + FI_BOOM), step + ": the parent whose delete failed is still there (its batch was rolled back)");
        return left;
    }

    /** Moves the made_at of every dry run 25 hours back, in the form the dialect stores it. */
    static void age25h(Fx fx) {
        String t = fx.d.meta("dry_runs");
        String before = fx.scalar("select made_at from " + t + " order by 1 desc limit 1");
        switch (fx.d) {
            case PG -> fx.update("update " + t + " set made_at = made_at - interval '25 hours'");
            case MY -> fx.update("update " + t + " set made_at = made_at - interval 25 hour");
            case SQ -> fx.update("update " + t + " set made_at = " + (before.contains("T")
                ? "strftime('%Y-%m-%dT%H:%M:%SZ', made_at, '-25 hours')" : "datetime(made_at, '-25 hours')"));
        }
        assertNotEquals(before, fx.scalar("select made_at from " + t + " order by 1 desc limit 1"), "setup: made_at moved");
    }

    // ---------------------------------------------------------------- helpers

    /** Drops every _dataforge table by hand (as a person would): the schema on Postgres, the prefixed tables elsewhere. */
    static void dropMetadata(Fx fx) {
        List<String> names = fx.metaTables();
        assertTrue(!names.isEmpty(), "setup: there is a _dataforge to drop");
        switch (fx.d) {
            case PG -> fx.adminSql("drop schema _dataforge cascade");
            case MY -> {
                List<String> s = new ArrayList<>(List.of("set foreign_key_checks = 0"));
                names.forEach(n -> s.add("drop table " + fx.d.meta(n)));
                fx.adminSql(s.toArray(new String[0]));
            }
            case SQ -> {
                List<String> s = new ArrayList<>(List.of("pragma foreign_keys = off"));
                names.forEach(n -> s.add("drop table " + fx.d.meta(n)));
                fx.adminSql(s.toArray(new String[0]));
            }
        }
        assertEquals(List.of(), fx.metaTables(), "setup: _dataforge is gone");
    }

    static String sha256(byte[]... parts) {
        try {
            MessageDigest m = MessageDigest.getInstance("SHA-256");
            for (byte[] p : parts) {
                m.update(p);
            }
            return HexFormat.of().formatHex(m.digest());
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    static byte[] bytes(Path p) {
        try {
            return Files.exists(p) ? Files.readAllBytes(p) : new byte[0];
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    /** The exit and the errors[].code set are exactly one code of these (the spec accepts either). */
    static void oneOf(String step, Result r, int exit, String... codes) {
        Set<String> ok = new TreeSet<>(Arrays.asList(codes));
        if (r.exit() != exit) {
            fail(step + ": expected exit " + exit + " with one of " + ok + " but " + r.describe());
        }
        if (r.json() == null || r.codes().size() != 1 || !ok.containsAll(r.codes())) {
            fail(step + ": expected exactly one error code, from " + ok + ", but " + r.describe());
        }
    }

    /** The failing codes of a readiness result: all of must, and nothing outside must and may. */
    static void failsWith(String step, Result r, Set<String> must, Set<String> may) {
        if (r.exit() != 1 || r.json() == null || r.json().path("ok").asBoolean(true)) {
            fail(step + ": expected exit 1 with ok:false and a JSON envelope but " + r.describe());
        }
        Set<String> got = r.codes();
        if (!got.containsAll(must)) {
            fail(step + ": expected the failing codes " + must + " but " + r.describe());
        }
        Set<String> allowed = new TreeSet<>(must);
        allowed.addAll(may);
        if (!allowed.containsAll(got)) {
            fail(step + ": codes " + got + " include ones that " + must + " does not imply (allowed " + allowed + "): " + r.describe());
        }
        JsonNode data = r.json().path("data");
        assertEquals(false, data.path("passed").asBoolean(true), step + ": data.passed");
        assertTrue(data.path("manual_checklist").isArray() && data.path("manual_checklist").size() > 0, step + ": the manual checklist is still printed");
    }

    static Set<String> set(String... s) {
        return new TreeSet<>(Arrays.asList(s));
    }

    /** The manual checklist keywords of CLASSIFY_PURGE_READINESS.md, one per item (nine items in the file). */
    static final List<String> CHECKLIST = List.of("files", "payment", "email", "logs", "cache", "search", "soft-delete", "materialised", "jobs");

    static void assertChecklist(String step, JsonNode list) {
        assertTrue(list.isArray(), step + ": data.manual_checklist is an array: " + list);
        String all = list.toString().toLowerCase(java.util.Locale.ROOT).replace("materialized", "materialised").replace("soft deleted", "soft-deleted");
        for (String k : CHECKLIST) {
            assertTrue(all.contains(k), step + ": the manual checklist has no item about '" + k + "': " + list);
        }
        assertTrue(list.size() >= 8, step + ": the checklist has " + list.size() + " items");
    }

    /** Lines of a Stream, to keep call sites short. */
    static <T> List<T> list(Stream<T> s) {
        return s.toList();
    }

    static String text(Path p) {
        return new String(bytes(p), StandardCharsets.UTF_8);
    }
}
